-- NotulenKu Expo prototype: isolated schema. Review RLS and auth before production.
create table if not exists public.expo_experiment_sessions (
 id text primary key, owner_id uuid not null references auth.users(id) on delete cascade,
 title text not null default 'Rapat baru', started_at timestamptz not null,
 ended_at timestamptz, status text not null default 'recorded', created_at timestamptz not null default now()
);
create table if not exists public.expo_experiment_segments (
 id bigint generated by default as identity primary key, session_id text not null references public.expo_experiment_sessions(id) on delete cascade,
 owner_id uuid not null references auth.users(id) on delete cascade, sequence integer not null,
 started_at timestamptz not null, ended_at timestamptz, storage_path text,
 status text not null, duration_ms bigint, attempts integer not null default 0, error text,
 transcript text, transcript_offset_ms bigint, unique(session_id,sequence)
);
create table if not exists public.expo_experiment_transcript_lines (
 id bigint generated by default as identity primary key, session_id text not null references public.expo_experiment_sessions(id) on delete cascade,
 segment_id bigint not null references public.expo_experiment_segments(id) on delete cascade,
 owner_id uuid not null references auth.users(id) on delete cascade, offset_ms bigint not null,
 speaker text not null, text text not null
);
alter table public.expo_experiment_sessions enable row level security;
alter table public.expo_experiment_segments enable row level security;
alter table public.expo_experiment_transcript_lines enable row level security;
create policy "own expo experiment sessions" on public.expo_experiment_sessions for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());
create policy "own expo experiment segments" on public.expo_experiment_segments for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());
create policy "own expo experiment lines" on public.expo_experiment_transcript_lines for all using (owner_id=auth.uid()) with check (owner_id=auth.uid());
